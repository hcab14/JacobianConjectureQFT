def family_V1(h0, h1):
    """Elementary z-shears  z -> z + y^3*(h0 + h1*u1):
    module data (A, B, C, D, E) of an automorphism (u1 is F-invariant)."""
    return (sp.S.One, sp.S.One, sp.S.Zero, sp.S.One, h0 + h1 * u1)


def family_V2(lam, nu):
    """Shears along the weight-(-1) invariant w = x*z - nu*y:
        F = (x, y + lam*x*w^3, z + lam*nu*w^3),      w o F = w,
    with explicit inverse (x, y - lam*x*w^3, z - lam*nu*w^3).  In the
    triangular coordinates (x, w, z) this is an elementary shear, so the
    family is tame.  Module data (A, B, C, D, E)."""
    return (sp.S.One,
            1 - lam * nu**3 * u1 + 3 * lam * nu**2 * u2 - 3 * lam * nu * u3,
            lam * u3,
            1 + 3 * lam * nu**3 * u1 - 3 * lam * nu**2 * u2 + lam * nu * u3,
            -lam * nu**4 + 0 * u1)


