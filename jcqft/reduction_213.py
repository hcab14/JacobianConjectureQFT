def orbit_point(t0, p0, q0):
    """The point Phi(t0, p0, q0) in C^3 (requires p0 != 0)."""
    return tuple(sp.simplify(c.subs({t: t0, p: p0, q: q0}))
                 for c in (p / t**2, t, q * t**3 / p**2))


def mechanism_witnesses(at, bt, et):
    """Solve the 2:1 locus {bt = et = 0, at != 0} and the 3:1 locus
    {at = bt = 0, et != 0} on {p != 0}.  Returns a dict
    {"2:1": [(p0, q0), ...], "3:1": [...]} of exact witnesses."""
    out = {"2:1": [], "3:1": []}
    for key, (f, g, h) in (("2:1", (bt, et, at)), ("3:1", (at, bt, et))):
        nf = sp.numer(sp.together(f))
        ng = sp.numer(sp.together(g))
        try:
            sols = sp.solve([nf, ng], [p, q], dict=True)
        except Exception:
            sols = []
        for s in sols:
            p0, q0 = s.get(p), s.get(q)
            if p0 is None or q0 is None:
                continue
            if p0.free_symbols or q0.free_symbols:
                continue
            if p0 == 0:
                continue
            hval = sp.simplify(h.subs({p: p0, q: q0}))
            if hval != 0:
                out[key].append((sp.nsimplify(p0), sp.nsimplify(q0)))
    return out
